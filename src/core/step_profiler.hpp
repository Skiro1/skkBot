// Сэмпл-профилировщик главного потока (05.11.2026, расследование холодного
// per-step 0.17-0.36ms при tps=10000).
//
// Зачем: HOT-таймеры показали, что весь бюджет кадра съедает
// `sched.update GD base` (наша доля 0.75-2.2ms/с), но ВНУТРИ шага GD имя
// виновника неизвестно - играют ли аллокации первой активации объектов,
// коллизии, окна объектов или что-то ещё. Сэмпл-профилировщик отвечает
// по имени: фоновый поток раз в ~1ms приостанавливает главный поток,
// снимает RIP и копит бакеты RVA. На стопе печатается топ по модулю
// GeometryDash.exe; офлайн-мапинг на функции - по биндингам
// (bindings/2.2091/GeometryDash.bro) и декомпиляту.
//
// Правила реестра офсетов не задеты: адреса только ЧИТАЮТСЯ для отчёта,
// ни один не используется для патча/хука. Инструмент diagnostic-only и
// включается тумблером "Step Profiler" (SETTINGS -> LOGGING, ключ
// gui_step_profiler, по умолчанию ВЫКЛ - замеры не должны искажаться).

#pragma once

namespace skkbot2::debug {

// Оптимизация из GUI (saved-ключ gui_step_profiler, default off).
bool stepProfilerOptIn();

// Дёшево: один атомарный fetch на вызов. Зовётся из горячего пути
// планировщика (главный поток) - фиксирует tid для сэмплера.
void profilerNoteMainThread();

// Начать сессию профилирования (no-op если выключен в GUI или уже идёт).
void profilerStart(const char* label);

// Остановить и напечатать топ RVA. No-op если не идёт.
void profilerStopAndReport();

}  // namespace skkbot2::debug

// BUG-102 v3: батч-контекст подшага — номер шага внутри кадра дисплея и dt
// этого кадра. Живая сессия 12:08/12:11 показала: позиции/держание бит-в-бит
// через f=415, но решение о контакте грав-портала разное (t0 флип 415->416,
// play 420->421), а единственный измеренный разнос миров — группировка
// подшагов по кадрам дисплея (rec ~1 шаг/кадр, play 2-3 шага/кадр). Счётчик
// позволяет в момент флипа и в probe-окне назвать позицию шага в батче.
//
// Game-thread only: простые глобалы без атомиков.
#pragma once

namespace skkbot2 {
namespace skcprobe {

    // Шаги physics с начала текущего кадра дисплея (0 = первый подшаг кадра).
    inline int g_batchStep = 0;
    // dt кадра дисплея, в котором идут текущие подшаги (0 = не сброшен).
    inline double g_frameDt = 0.0;

    // Один вызов на кадр дисплея, ДО цикла подшагов (из update-хука).
    inline void beginFrame(double dt) {
        g_batchStep = 0;
        g_frameDt = dt;
    }

    // Один вызов на подшаг (из processCommands-хука, до печати probe).
    inline void noteStep() {
        ++g_batchStep;
    }

    // BUG-102 v3: кэш движущегося грав-портала (объект 2926 в WEB21) для
    // probe-окна. Заполняется из portal-see хука; позиция/скейл портала в
    // probe-окне называет, когда timeline движущегося объекта расходится
    // между мирами (сессия 14:19: portal 2926 имел РАЗНЫЙ rect в rec/play
    // на одном тике - канал сдвига флипа 739 vs 736).
    inline void* g_probePortal = nullptr;
    inline int g_probePortalId = 0;

}  // namespace skcprobe
}  // namespace skkbot2

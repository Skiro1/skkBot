#pragma once

#include <cstdint>
#include <vector>

namespace skk::skc {

// ---------------------------------------------------------------------------
// skc_rng — полный детерминизм рандома SKC (порт ключевых механизмов SKK).
//
// SKC едет на входах поверх ванильной физики, но три потока рандома GD вместе
// с сидами слоёв остаются глобальным состоянием, которое зависит от истории
// сессии (меню жрёт LCG, вход в уровень, переходы, чужие дрова). SKK закрывает
// это пятью уровнями (refreshRngState / forceLayerSeeds / advRandomReseed /
// якоря rngBoundaries / рантайм-аудит fast_rand между якорями). SKC-порт:
//
//   1. forceLayerSeeds — после ванильного resetLevel (только attempt-from-
//      start, БЕЗ стича) сид-пара GJBaseGameLayer::m_randomSeed /
//      m_replayRandSeed заново выставляется константой в ОБОИХ мирах, так что
//      рантайм-роллы, которые их читают, совпадают. Нет activeSk — константа
//      от формата, а не от SKK-макроса.
//   2. Журнал RNG в payload SKC: при записи каждый якорь (каждый кадр
//      записанного ввода + каждые kRngIdleInterval кадров простоя + первый
//      тик после шва попытки/чекпоинта) пишет
//      тройку live-состояний (primary LCG 0x90BF68, teleport LCG 0x90BFF0,
//      собственная shake-цепочка бота) — но ТОЛЬКО если хотя бы один поток
//      изменился с прошлого записанного якоря: восстановление того же
//      состояния смысла не имеет, а чаще всего все три потока неизменны, и
//      тихая пауза между кликами не хранит вообще ничего. Плейбэк восстанав-
//      ливает записанные состояния на тех же кадрах (rng relock) — дрейф
//      цепочек между якорями гасится в пределах одного окна простоя. adv-
//      рандомы (2068/1912/3607) в журнал не пишутся: их пересев детермини-
//      рован от постоянного сида (lazy-init rng_hooks унутри SKK-движка).
//      Плотные якоря обязательны: разреженная сетка «как Silicate» убита
//      живым ретестом 20:52 ('Mk3') — расход растёт быстрее сетки и убивает
//      плейбэк между якорями.
//   3. Формат: хвост ПОСЛЕ самозавершающегося range-потока, со своим 8-байт-
//      ным магиком и объёмом в заголовке хвоста. Ни одного бита в knob'ах —
//      legacy-файлы (без хвоста) декодируются байт-в-байт как раньше: конец
//      потока распознаётся по END-символу, потраченные байты считает
//      RangeDecoder::consumedBytes(), всё, что осталось после него — хвост.
//
// Размер хвоста: v5 (12.11) — v4-машина (run-length + теги
// same/advance/raw/pin) + канонизация shake до 31 бита: вывод цепочки
// (lcgOutput = биты 16..30) зависит только от младших 31 бита состояния
// (переносы LCG идут вверх), поэтому state & 0x7FFFFFFF воспроизводит все
// будущие выводы бит-в-бит — lossless по поведению при 31-битном shake.
// Синтетика self-test: v5 346 B на 1232 якорей (0.28 Б/якорь); живой
// профиль — десятки байт на весь уровень, точное число печатает
// self-test при старте и appendRngJournal при каждом сохранении.
//
// Размер хвоста ≈ 28 B на якорь, якорь появляется только там, где цепочки
// реально кусались: +14 КБ на 28k-кадровый уровень с 388 кликами в худшем
// случае, обычно заметно меньше. Сжатие (LZ по цепочкам) — только если живой
// замер покажет, что оно того стоит.
// ---------------------------------------------------------------------------

// Константа пина SKC (BUG-107, skc_hooks). Она же — сид пары слоёв: никаких
// activeSk у SKC нет, значит сид один и одинаков в record/play.
inline constexpr uint64_t kSkcLayerSeed = 0x2545F491ULL;

// Версия хвоста и окно якорей простоя.
inline constexpr uint32_t kRngTailVersion = 1u;
inline constexpr uint32_t kRngIdleInterval = 240u;

struct RngJournalEntry {
    uint32_t frame = 0;
    uint64_t primary = 0;
    uint64_t teleport = 0;
    uint64_t shake = 0;
    bool operator==(const RngJournalEntry&) const = default;
};

// --- хвост формата ---------------------------------------------------------

// Дописывает журнал последним блоком байтов (после range-потока). Пустой
// журнал не пишет ровно ничего — файл обычного макроса не меняется.
void appendRngJournal(std::vector<uint8_t>& bytes,
                      const std::vector<RngJournalEntry>& journal);

// Разбирает хвост из оставшихся после range-потока байтов. false, если хвост
// на месте, но битый — тогда макрос всё равно грузится, только без журнала
// (ввода это не касается).
bool parseRngJournal(const uint8_t* data, size_t size,
                     std::vector<RngJournalEntry>& out);
// после boundary. Магия ищется с конца среза (последнее вхождение),
// найденное смещение логируется — дальнейший парс строгий (version/count
// проверяются как раньше). Пустой хвост тоже отчёт: «file carries none».
bool locateAndParseRngJournal(const uint8_t* data, size_t size,
                              std::vector<RngJournalEntry>& out,
                              size_t back = 0);

// --- движок (запись / плейбэк) ---------------------------------------------

// После ванильного resetLevel (non-stitch, оба мира) — сиды слоёв в константу.
void forceLayerSeeds();

// Якорь при записи. Вызывается каждый шаг processCommands; `typedInput` —
// был ли с прошлого шага записан ввод. Кандидат = typedInput ИЛИ окно простоя;
// хранится только при изменившейся тройке.
void journalRecordTick(bool typedInput);

// Релок при плейбэке: восстанавливает все якоря с frame <= текущего кадра
// (курсор), живой side-эффект только при расхождении.
void journalPlaybackTick();

// Сводка по журналу на момент остановки/смерти плейбэка: сколько якорей
// прошёл курсор, сколько тихо совпало, сколько сделали релок. Отличает
// «журнал молчал и всё совпало» от «журнал вообще не работал». Печатает
// строку всегда, когда журнал непуст (пустой журнал — тоже stdout-строка).
void journalPlaybackCounters(const char* reason);

// Сброс движка при рестарте попытки. `wipe` — новая попытка с нуля: журнал
// записи обнуляется (все якоря принадлежали мёртвой попытке), курсор плейбэка
// — в 0. `!wipe` — стич: якоря до границы выпадают вместе с отрезанным
// вводом, курсор плейбэка — в 0.
void journalResetAttempt(uint32_t boundaryFrame, bool wipe);

// Только курсор плейбэка в 0 (новый макрос принят load/adopt/startPlayback —
// старый курсор принадлежал другой сессии). Записанный журнал не трогает.
void journalResetCursor();

// Startup self-test: синтетический журнал (LCG-шаги, константный teleport,
// raw-выбросы) - round-trip бит-в-бит + метрика сжатия. См. main.cpp.
[[nodiscard]] bool selfTestRngJournal();

} // namespace skk::skc
